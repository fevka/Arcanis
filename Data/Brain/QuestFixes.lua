local side = UnitFactionGroup and UnitFactionGroup("player")
for q, f in pairs(B.fix) do
  if f.gone then
    B.graph[q], B.givers[q] = nil, nil
  else
    if f.lv then
      B.graph[q] = B.graph[q] or {}
      B.graph[q].lv = f.lv
      if B.givers[q] then B.givers[q][3] = f.lv end
    end
    if f.ql and B.givers[q] then B.givers[q][2] = f.ql end
    if f.need then
      local g = B.graph[q] or {}
      B.graph[q] = g
      g.any = g.any or {}
      for _, p in ipairs(f.need) do g.any[#g.any + 1] = p end
    end
    if f.req then   -- onkosulun kendisi yanlis: grafikteki "biri" / "hepsi" listesi bununla degisir
      local g = B.graph[q] or {}
      B.graph[q] = g
      g.any, g.all = {}, nil
      for _, p in ipairs(f.req) do g.any[#g.any + 1] = p end
    end
    if f.all then
      local g = B.graph[q] or {}
      B.graph[q] = g
      g.all = g.all or {}
      for _, p in ipairs(f.all) do g.all[#g.all + 1] = p end
    end
    if f.noex and B.graph[q] then B.graph[q].ex = nil end   -- dislama listesi yanlis: kaldir
    if f.bc then   -- yonlendirme: hedef gorev alininca bu gorev verilmez
      local g = B.graph[q] or {}
      B.graph[q] = g
      g.bc = f.bc
    end
    local v = B.givers[q]
    if v and f.rm then v[4] = f.rm end
    if v and f.npc then v[6], v[7], v[8], v[9] = f.npc, f.zone, f.x, f.y end
    -- taraf basina veren (sinif gorevleri: her tarafin kendi egitmeni); taraf bilinmiyorsa (Skyborne secimden once) taban
    local r = v and f.fac and side and f.fac[side]
    if r then v[6], v[7], v[8], v[9] = r[1], r[2], r[3], r[4] end
    if f.more then B.moreGivers[q] = f.more end
  end
end

